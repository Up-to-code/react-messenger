export function translate(locale, key, values = {}) {
  const value = strings[locale]?.[key] ?? strings.en[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}
export const LocaleContext = createContext({
  locale: "en",
  t: (key, values) => translate("en", key, values),
});
export const useLocale = () => useContext(LocaleContext);
export function displayName(conversation, t) {
  return conversation.id === "agent"
    ? t("agent")
    : t("language") === "اللغة" && conversation.nameAr
      ? conversation.nameAr
      : conversation.name;
}
